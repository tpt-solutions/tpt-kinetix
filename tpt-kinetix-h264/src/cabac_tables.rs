/// macroblock -- continues via `decode_cabac_intra_mb_type(sl, 17, 0)`,
/// which reuses ctxIdx 17..=20 for the (shared-with-I-slice) suffix
/// binarization. Total range 14..=20 (7 contexts) also matches the source's
/// own `/* 11 - 23 */` block-comment boundary (3 mb_skip_flag + 7 mb_type +
/// 3 sub_mb_type = 13 entries).
pub const MB_TYPE_P_CTX: usize = 14;

/// `sub_mb_type` (P, SP slices), ctxIdx 21..=23 (Table 9-11, ctxIdxOffset
/// 21). Confirmed directly from `decode_cabac_p_mb_sub_type`'s
/// `cabac_state[21]`, `[22]`, `[23]`.
pub const SUB_MB_TYPE_P_CTX: usize = 21;

/// `mb_skip_flag` (B slices), ctxIdx 24..=26 (Table 9-11, ctxIdxOffset 24).
/// Confirmed directly from `decode_cabac_mb_skip`, which adds 13 to `ctx`
/// for B slices before indexing `cabac_state[11+ctx]` -- i.e. B reuses the
/// same condTermFlagA/condTermFlagB derivation as P/SP (§9.3.3.1.1.1), just
/// at a +13 ctxIdx offset, so [`crate::entropy::MbSkipNeighbors`]'s existing
/// `ctx_idx_inc()` logic is reused unchanged for B slices too.
pub const MB_SKIP_FLAG_B_CTX: usize = 24;

/// `mb_type` (B slices), ctxIdx 27..=35 (Table 9-11, ctxIdxOffset 27).
/// Confirmed from the inline B-slice `mb_type` dispatch (`cabac_state[27+ctx]`
/// for `ctx` 0..=5, i.e. ctxIdx 27..=32), which -- when the bit pattern
/// indicates an I-coded macroblock -- continues via
/// `decode_cabac_intra_mb_type(sl, 32, 0)`, reusing ctxIdx 32..=35 for the
/// suffix. Total range 27..=35 (9 contexts) also matches the source's own
/// `/* 24 - 39 */` block-comment boundary (3 mb_skip_flag + 9 mb_type + 4
/// sub_mb_type = 16 entries).
pub const MB_TYPE_B_CTX: usize = 27;

/// `sub_mb_type` (B slices), ctxIdx 36..=39 (Table 9-11, ctxIdxOffset 36).
/// Confirmed directly from `decode_cabac_b_mb_sub_type`'s
/// `cabac_state[36]`, `[37]`, `[38]`, `[39]`.
pub const SUB_MB_TYPE_B_CTX: usize = 36;

/// `mvd` horizontal (`mvd_l0[][][0]`/`mvd_l1[][][0]`) component, ctxIdx
/// 40..=46 (Table 9-11, ctxIdxOffset 40). Confirmed directly from the
/// `DECODE_CABAC_MB_MVD` macro's `decode_cabac_mb_mvd(sl, 40, ...)` call
/// (bin 0 uses `ctxbase + {0,1,2}`; the truncated-unary continuation bins
/// use `ctxbase + 3` through `ctxbase + 6`, reusing the last one for bins
/// beyond the context-coded prefix before the UEG3 bypass suffix).
pub const MVD_X_CTX: usize = 40;

/// `mvd` vertical (`mvd_l0[][][1]`/`mvd_l1[][][1]`) component, ctxIdx
/// 47..=53 (Table 9-11, ctxIdxOffset 47). Confirmed directly from
/// `decode_cabac_mb_mvd(sl, 47, ...)` in the same macro as [`MVD_X_CTX`].
pub const MVD_Y_CTX: usize = 47;

/// `ref_idx_l0`/`ref_idx_l1`, ctxIdx 54..=59 (Table 9-11, ctxIdxOffset 54).
/// Confirmed directly from `decode_cabac_mb_ref`'s `cabac_state[54+ctx]`:
/// `ctx` 0..=3 from left/top neighbour ref indices/direct-mode flags (ctxIdx
/// 54..=57), then the truncated-unary continuation reuses ctxIdx 58 for the
/// first extra bin and ctxIdx 59 for all bins after that.
pub const REF_IDX_CTX: usize = 54;

/// `coded_block_flag` ctxIdxOffset per `ctxBlockCat` 0..=4 (Table 9-24..9-28
/// family): `[LumaDC, LumaAC, Luma4x4, ChromaDC, ChromaAC]`. ctxIdxInc =
/// `(left_coded as usize) + 2*(top_coded as usize)`.
///
/// No `ctxBlockCat == 5` (Luma8x8, see [`CAT_LUMA_8X8`]) entry: per FFmpeg's
/// `decode_cabac_residual_nondc` (`if( (cat != 5 || CHROMA444(h)) && ...)`),
/// `coded_block_flag` is only read for Luma8x8 blocks when
/// `ChromaArrayType == 3` (4:4:4, out of this crate's scope); for the
/// monochrome/4:2:0/4:2:2 case this crate targets it is never signalled and
/// is implicitly inferred present, matching how `coded_block_pattern`
/// already gates 8x8-block presence at the same (per-8x8-region) granularity
/// the residual would otherwise redundantly re-signal.
pub const CBF_CTX_BASE: [usize; 5] = [85, 89, 93, 97, 101];

/// `significant_coeff_flag` ctxIdxOffset per `ctxBlockCat` 0..=5 (frame
/// coding only -- no MBAFF/field support): `[LumaDC, LumaAC, Luma4x4,
/// ChromaDC, ChromaAC, Luma8x8]`. For cats 0..=4, ctxIdxInc = raw scan
/// position; for cat 5 (Luma8x8) it does **not** equal the raw scan
/// position -- see [`SIG_COEFF_CTX_INC_8X8_FRAME`].
pub const SIG_COEFF_CTX_BASE: [usize; 6] = [105, 120, 134, 149, 152, 402];

/// `last_significant_coeff_flag` ctxIdxOffset per `ctxBlockCat` 0..=5 (frame
/// coding only). For cats 0..=4, ctxIdxInc = raw scan position; for cat 5
/// (Luma8x8) see [`LAST_COEFF_CTX_INC_8X8_FRAME`].
pub const LAST_COEFF_CTX_BASE: [usize; 6] = [166, 181, 195, 210, 213, 417];

/// `coeff_abs_level_minus1` ctxIdxOffset per `ctxBlockCat` 0..=5. Combined
/// with [`COEFF_ABS_LEVEL1_CTX`] / [`COEFF_ABS_LEVELGT1_CTX`] via the
/// `node_ctx` state machine (§9.3.3.1.3); the node_ctx state machine itself
/// is identical for cat 5 (Luma8x8) -- only the base offset changes.
pub const COEFF_ABS_LEVEL_M1_CTX_BASE: [usize; 6] = [227, 237, 247, 257, 266, 426];

/// `node_ctx` (0..=7) -> relative ctxIdxInc for the "level == 1" bin of
/// `coeff_abs_level_minus1`'s UEG0 binarization.
pub const COEFF_ABS_LEVEL1_CTX: [usize; 8] = [1, 2, 3, 4, 0, 0, 0, 0];

/// `node_ctx` (0..=7) -> relative ctxIdxInc for the "level > 1" bins.
pub const COEFF_ABS_LEVELGT1_CTX: [usize; 8] = [5, 5, 5, 5, 6, 7, 8, 9];

/// `node_ctx` state transition after decoding a level: `[level==1,
/// level>1][node_ctx] -> next node_ctx`.
pub const COEFF_ABS_LEVEL_TRANSITION: [[usize; 8]; 2] = [
    [1, 2, 3, 3, 4, 5, 6, 7],
    [4, 4, 4, 4, 5, 6, 7, 7],
];

/// Block categories (`ctxBlockCat`, spec Table 9-42) used to index the
/// per-category context bases above.
pub const CAT_LUMA_DC: usize = 0;
pub const CAT_LUMA_AC: usize = 1;
pub const CAT_LUMA_4X4: usize = 2;
pub const CAT_CHROMA_DC: usize = 3;
pub const CAT_CHROMA_AC: usize = 4;

/// Luma 8x8-transform residual block (`ctxBlockCat` 5, spec Table 9-42),
/// used only when `transform_8x8_mode_flag` is set for the macroblock (this
/// crate currently gates that path off elsewhere -- see `!pps.transform_8x8_mode_flag`
/// in the slice parser -- so nothing constructs a decoder for this category
/// yet; these are context-index *tables* only, added ahead of that gate
/// being lifted). Deliberately **absent** from [`CBF_CTX_BASE`] -- see that
/// constant's doc comment for why `coded_block_flag` isn't separately coded
/// for this category in the (non-4:4:4) case this crate targets.
pub const CAT_LUMA_8X8: usize = 5;

/// `significant_coeff_flag` ctxIdxInc indirection for `ctxBlockCat` 5
/// (Luma8x8, frame coding only): index = scan position (0..=62, since
/// Luma8x8 has `cMax = 64` and the final position's significance is
/// implicit), value = ctxIdxInc (0..=14, i.e. 15 distinct contexts) to add
/// to [`SIG_COEFF_CTX_BASE`]`[CAT_LUMA_8X8]`. Unlike `ctxBlockCat` 0..=4
