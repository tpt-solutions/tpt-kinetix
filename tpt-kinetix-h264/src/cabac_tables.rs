#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn mb_qp_delta_init_matches_known_values() {
        // Cross-checked independently against the pre-existing MB_QP_DELTA_INIT
        // values from the original (engine-only) CABAC work.
        assert_eq!(CABAC_CTX_INIT_I[60], (0, 41));
        assert_eq!(CABAC_CTX_INIT_I[61], (0, 63));
        assert_eq!(CABAC_CTX_INIT_I[62], (0, 63));
        assert_eq!(CABAC_CTX_INIT_I[63], (0, 63));
    }

    #[test]
    fn table_has_1024_entries() {
        assert_eq!(CABAC_CTX_INIT_I.len(), 1024);
    }

    // ---- CABAC_CTX_INIT_PB0/1/2 (Phase D.1) ----

    #[test]
    fn pb_tables_have_1024_entries() {
        assert_eq!(CABAC_CTX_INIT_PB0.len(), 1024);
        assert_eq!(CABAC_CTX_INIT_PB1.len(), 1024);
        assert_eq!(CABAC_CTX_INIT_PB2.len(), 1024);
    }

    #[test]
    fn pb_tables_share_the_common_prefix_with_the_i_table() {
        // ctxIdx 0..=10 (mb_type-I's neighbour-independent lead-in contexts,
        // Table 9-12) are identical across all four tables in FFmpeg's
        // source -- spot-check a few to catch a wholesale mistranscription
        // (e.g. accidentally starting the PB extraction at the wrong offset).
        for idc_table in [&CABAC_CTX_INIT_PB0, &CABAC_CTX_INIT_PB1, &CABAC_CTX_INIT_PB2] {
            assert_eq!(idc_table[0], CABAC_CTX_INIT_I[0]);
            assert_eq!(idc_table[6], CABAC_CTX_INIT_I[6]);
            assert_eq!(idc_table[10], CABAC_CTX_INIT_I[10]);
        }
    }

    #[test]
    fn pb_tables_mb_qp_delta_matches_i_table() {
        // mb_qp_delta (ctxIdx 60..=63) is shared across I/P/B slice types
        // (Table 9-20 doesn't vary its ctxIdxOffset by slice type), so all
        // four tables should agree here too.
        for idc_table in [&CABAC_CTX_INIT_PB0, &CABAC_CTX_INIT_PB1, &CABAC_CTX_INIT_PB2] {
            assert_eq!(&idc_table[60..64], &CABAC_CTX_INIT_I[60..64]);
        }
    }

    #[test]
    fn pb0_mb_skip_flag_mb_type_sub_mb_type_p_init_matches_known_values() {
        // ctxIdx 11..=23 for cabac_init_idc == 0, cross-checked against
        // FFmpeg's `cabac_context_init_PB[0]` (fetched this session).
        assert_eq!(CABAC_CTX_INIT_PB0[MB_SKIP_FLAG_P_CTX], (23, 33));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_SKIP_FLAG_P_CTX + 1], (23, 2));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_SKIP_FLAG_P_CTX + 2], (21, 0));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_TYPE_P_CTX], (1, 9));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_TYPE_P_CTX + 6], (1, 62));
        assert_eq!(CABAC_CTX_INIT_PB0[SUB_MB_TYPE_P_CTX], (12, 49));
        assert_eq!(CABAC_CTX_INIT_PB0[SUB_MB_TYPE_P_CTX + 2], (17, 50));
    }

    #[test]
    fn pb0_mb_skip_flag_mb_type_sub_mb_type_b_init_matches_known_values() {
        // ctxIdx 24..=39 for cabac_init_idc == 0.
        assert_eq!(CABAC_CTX_INIT_PB0[MB_SKIP_FLAG_B_CTX], (18, 64));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_TYPE_B_CTX], (26, 67));
        assert_eq!(CABAC_CTX_INIT_PB0[MB_TYPE_B_CTX + 8], (1, 62));
        assert_eq!(CABAC_CTX_INIT_PB0[SUB_MB_TYPE_B_CTX], (-6, 86));
        assert_eq!(CABAC_CTX_INIT_PB0[SUB_MB_TYPE_B_CTX + 3], (9, 45));
    }

    #[test]
    fn pb0_mvd_ref_idx_init_matches_known_values() {
        // ctxIdx 40..=59 for cabac_init_idc == 0.
        assert_eq!(CABAC_CTX_INIT_PB0[MVD_X_CTX], (-3, 69));
        assert_eq!(CABAC_CTX_INIT_PB0[MVD_Y_CTX], (0, 58));
        assert_eq!(CABAC_CTX_INIT_PB0[REF_IDX_CTX], (-7, 67));
        assert_eq!(CABAC_CTX_INIT_PB0[REF_IDX_CTX + 5], (1, 58));
    }

    #[test]
    fn pb1_and_pb2_mb_skip_flag_p_differs_from_pb0() {
        // Direct proof (not assumption) that mb_skip_flag's context init is
        // cabac_init_idc-dependent, per the task's "confirm this is really
        // PB-idc-dependent" requirement: ctxIdx 11 (the first of the 3
        // mb_skip_flag-P contexts) has a different (m, n) pair in each of
        // the three idc tables.
        let ctx11 = [
            CABAC_CTX_INIT_PB0[MB_SKIP_FLAG_P_CTX],
            CABAC_CTX_INIT_PB1[MB_SKIP_FLAG_P_CTX],
            CABAC_CTX_INIT_PB2[MB_SKIP_FLAG_P_CTX],
        ];
        assert_eq!(ctx11, [(23, 33), (22, 25), (29, 16)]);
        assert_ne!(ctx11[0], ctx11[1]);
        assert_ne!(ctx11[1], ctx11[2]);
    }

    // ---- Luma8x8 (ctxBlockCat 5) residual contexts (Phase D.1) ----

    #[test]
    fn luma_8x8_context_bases_extend_the_existing_five_categories() {
        assert_eq!(SIG_COEFF_CTX_BASE.len(), 6);
        assert_eq!(LAST_COEFF_CTX_BASE.len(), 6);
        assert_eq!(COEFF_ABS_LEVEL_M1_CTX_BASE.len(), 6);
        // cats 0..=4 unchanged (additive-only constraint).
        assert_eq!(&SIG_COEFF_CTX_BASE[0..5], &[105, 120, 134, 149, 152]);
        assert_eq!(&LAST_COEFF_CTX_BASE[0..5], &[166, 181, 195, 210, 213]);
        assert_eq!(&COEFF_ABS_LEVEL_M1_CTX_BASE[0..5], &[227, 237, 247, 257, 266]);
        // cat 5 (Luma8x8), cross-checked against FFmpeg's
        // significant_coeff_flag_offset/last_coeff_flag_offset/coeff_abs_level_m1_offset
        // frame-coding rows at index [5].
        assert_eq!(SIG_COEFF_CTX_BASE[CAT_LUMA_8X8], 402);
        assert_eq!(LAST_COEFF_CTX_BASE[CAT_LUMA_8X8], 417);
        assert_eq!(COEFF_ABS_LEVEL_M1_CTX_BASE[CAT_LUMA_8X8], 426);
    }

    #[test]
    fn sig_coeff_ctx_inc_8x8_frame_has_63_in_range_entries() {
        assert_eq!(SIG_COEFF_CTX_INC_8X8_FRAME.len(), 63);
        // ctxIdxInc range for Luma8x8 significance-map, frame coding, is
        // 0..=14 (15 contexts) per spec Table 9-43.
        assert!(SIG_COEFF_CTX_INC_8X8_FRAME.iter().all(|&v| v <= 14));
        assert_eq!(SIG_COEFF_CTX_INC_8X8_FRAME[0], 0);
        assert_eq!(SIG_COEFF_CTX_INC_8X8_FRAME[1], 1);
        assert_eq!(SIG_COEFF_CTX_INC_8X8_FRAME[21], 3);
        assert_eq!(SIG_COEFF_CTX_INC_8X8_FRAME[62], 12);
    }

    #[test]
    fn last_coeff_ctx_inc_8x8_frame_has_63_in_range_entries() {
        assert_eq!(LAST_COEFF_CTX_INC_8X8_FRAME.len(), 63);
        // ctxIdxInc range for Luma8x8 last-significant-coeff, frame coding,
        // is 0..=8 (9 contexts) per spec Table 9-43.
        assert!(LAST_COEFF_CTX_INC_8X8_FRAME.iter().all(|&v| v <= 8));
        assert_eq!(LAST_COEFF_CTX_INC_8X8_FRAME[0], 0);
        assert_eq!(LAST_COEFF_CTX_INC_8X8_FRAME[15], 1);
        assert_eq!(LAST_COEFF_CTX_INC_8X8_FRAME[16], 2);
        assert_eq!(LAST_COEFF_CTX_INC_8X8_FRAME[62], 8);
    }
}
