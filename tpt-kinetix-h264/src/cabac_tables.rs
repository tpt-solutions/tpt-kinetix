//! CABAC context-initialisation tables and per-syntax-element ctxIdx layout
//! (ITU-T H.264 Tables 9-12..9-33) for the I-slice subset implemented in
//! [`crate::entropy`].
//!
//! `CABAC_CTX_INIT_I` was extracted from FFmpeg's `libavcodec/h264_cabac.c`
//! `cabac_context_init_I[1024][2]` table -- the same cross-check approach this
//! crate's CAVLC tables already use (see `GOLOMB_TO_INTER_CBP` in
//! `slice_data.rs`). These numeric constants are mandated by the ITU-T H.264
//! spec for interoperability, so every independent decoder reproduces the
//! same values; only the ctxIdx *usage* (which bin maps to which context,
//! and how ctxIdxInc is derived from neighbours) is implementation logic,
//! which is ported and tested independently in `entropy.rs`/`slice_data.rs`.
//!
//! Only entries actually consumed by the I-slice syntax elements implemented
//! this phase are exercised (see the offset constants below); the remaining
//! entries are P/B-slice-only (`mb_skip_flag`, `mb_type` P/B, `sub_mb_type`,
//! `ref_idx`, `mvd`, ...) and are kept for a future Phase D.4 without being
//! consumed yet.

