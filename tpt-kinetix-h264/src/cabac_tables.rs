/// `mb_type` (I-slice), ctxIdx 3..=10 (Table 9-11). Bin 0 uses `ctx + {0,1,2}`
/// from the left/top neighbour's mb_type; the remaining bins are fixed
/// offsets from `MB_TYPE_I_CTX + 2` (see `entropy.rs` for the exact mapping,
/// cross-checked against FFmpeg's `decode_cabac_intra_mb_type`).
pub const MB_TYPE_I_CTX: usize = 3;

/// `intra_chroma_pred_mode`, ctxIdx 64..=67 (Table 9-15). Bin 0 uses
/// `ctx + {0,1,2}` from left/top neighbour chroma pred mode; bins 1-2 reuse
/// `ctx + 3`.
pub const CHROMA_PRED_MODE_CTX: usize = 64;

/// `prev_intra4x4_pred_mode_flag`, ctxIdx 68 (Table 9-15): a single fixed
/// context, no ctxIdxInc.
