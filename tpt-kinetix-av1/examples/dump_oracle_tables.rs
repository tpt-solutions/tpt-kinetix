// Dumps the coefficient-relevant default tables + constants from this crate
// as a Python module (via `{:?}` debug formatting, which is valid Python list
// syntax). The resulting file is consumed by `tools/av1_oracle` to build an
// independent re-implementation of `coeffs()` whose *control flow* (context
// derivation + symbol read order) is hand-written from the spec, while the
// table *values* come from this crate. This guarantees the oracle's table data
// exactly matches what Kinetix decodes, so any divergence it finds against a
// real tile is a genuine control-flow / context bug (a table-value bug would
// need a spec-PDF re-transcription pass, tracked separately).
//
// Run: cargo run -p tpt-kinetix-av1 --example dump_oracle_tables > ../../tools/av1_oracle/cdf_tables_gen.py

use tpt_kinetix_av1::coeff_tables::*;
use tpt_kinetix_av1::entropy_cdf::*;

