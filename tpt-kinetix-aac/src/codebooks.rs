//! AAC Huffman noiseless-coding codebooks, transcribed from ISO/IEC 14496-3:2009
//! Annex 4.A (Tables 4.A.1 through 4.A.12).
//!
//! Each spectral/scalefactor codebook is stored as a slice of (code, length)
//! pairs indexed by the codeword index printed in the spec. "code" holds the
//! MSB-first codeword bit pattern in its low "length" bits. Decoding walks the
//! bitstream and matches the longest prefix, which is unambiguous because the
//! tables form a valid prefix code.
//!
//! The (w, x, y, z) spectral values are derived from the codeword index with the
//! spec dim/lav/unsigned mapping (subclause 4.6.3.3), so only the codeword
//! tables are needed here.
//!
//! Provenance: data transcribed directly from the public standard, not from any
//! third-party (MPL/LGPL) implementation.

