/// Codebook parameters from Table 4.151: (dimension, lav, unsigned_cb).
///
/// "dimension" is 4 for the four-tuple codebooks (1..4) and 2 for the pair
/// codebooks (5..11). "unsigned_cb" is true when the codebook carries unsigned
/// magnitudes (sign bits follow the codeword). sect_cb values 0, 12..=15
/// (zero / reserved / intensity / noise) are not Huffman spectral codebooks.
fn book_params(sect_cb: u8) -> Option<(u32, i32, bool)> {
    match sect_cb {
        1 => Some((4, 1, false)),
        2 => Some((4, 1, false)),
        3 => Some((4, 2, true)),
        4 => Some((4, 2, true)),
        5 => Some((2, 4, false)),
        6 => Some((2, 4, false)),
        7 => Some((2, 7, true)),
        8 => Some((2, 7, true)),
        9 => Some((2, 12, true)),
        10 => Some((2, 12, true)),
        11 => Some((2, 16, true)),
        _ => None,
    }
}

/// Decode one Huffman codeword from "book", returning its codeword index.
///
/// Walks the bitstream MSB-first, accumulating bits until they match a complete
/// codeword in "book". Returns "None" on stream exhaustion or if no prefix of the
/// accumulated bits matches any codeword within 19 bits.
pub fn decode_codeword(reader: &mut BitReader, book: &[(u32, u8)]) -> Option<usize> {
    let mut cur: u32 = 0;
    let mut nbits: u32 = 0;
    loop {
        let bit = reader.read_bit()? as u32;
        cur = (cur << 1) | bit;
        nbits += 1;
        let mask = (1u32 << nbits) - 1;
        for (i, &(code, len)) in book.iter().enumerate() {
            if (len as u32) == nbits && (cur & mask) == code {
                return Some(i);
            }
        }
        if nbits > 19 {
            return None;
        }
    }
}

/// Translate a codeword index into its (w, x, y, z) spectral n-tuple per the
/// spec subclause 4.6.3.3 formula.
///
/// For signed codebooks ("unsigned == false") the returned values are already
/// signed. For unsigned codebooks they are non-negative magnitudes and the
/// caller must apply the trailing sign bits (and, for the ESC book, the escape
/// sequences).
fn idx_to_values(idx: i64, dim: u32, lav: i32, unsigned: bool) -> [i32; 4] {
    let (modv, off) = if unsigned {
        (lav as i64 + 1, 0)
    } else {
        (2 * lav as i64 + 1, lav as i64)
    };
    if dim == 4 {
        let m3 = modv * modv * modv;
        let w = idx / m3 - off;
        let idx = idx - (w + off) * m3;
        let m2 = modv * modv;
        let x = idx / m2 - off;
        let idx = idx - (x + off) * m2;
        let y = idx / modv - off;
        let z = idx - (y + off) * modv;
        [w as i32, x as i32, y as i32, z as i32]
    } else {
        let y = idx / modv - off;
        let z = idx - (y + off) * modv;
        [0, 0, y as i32, z as i32]
    }
}

/// Apply a sign bit to a non-negative magnitude (used by unsigned codebooks).
fn apply_sign(reader: &mut BitReader, mag: i32) -> Option<i32> {
    if mag == 0 {
        return Some(0);
    }
    let negative = reader.read_bit()? == 1;
    Some(if negative { -mag } else { mag })
}

/// Apply a sign bit followed by the ESC-book escape sequence (book 11 only).
///
/// "raw" is the unsigned magnitude decoded from the index (0..=16). A "raw" of
/// 16 is the ESC_FLAG, signalling an escape_sequence: N "1" bits, a "0"
/// separator, then an "N+4"-bit word giving 2^(N+4) + word. The sign bit is
/// read before the escape sequence (spec subclause 4.6.3.3).
fn apply_sign_esc(reader: &mut BitReader, raw: i32) -> Option<i32> {
    if raw == 0 {
        return Some(0);
    }
    let negative = reader.read_bit()? == 1;
    let mag: u32 = if raw == 16 {
        let mut n: u32 = 0;
        while reader.read_bit()? == 1 {
            n += 1;
        }
        let word = reader.read_bits(n + 4)?;
        (1u32 << (n + 4)) + word
    } else {
        raw as u32
    };
    Some(if negative { -(mag as i32) } else { mag as i32 })
}

/// Decode one spectral n-tuple for "sect_cb", returning [w, x, y, z].
///
/// For pair codebooks (5..11) only "y" and "z" are meaningful; "w" and "x" are
/// zero. Handles unsigned sign bits and the book-11 escape sequence.
pub fn decode_spectral_quad(reader: &mut BitReader, sect_cb: u8) -> Option<[i32; 4]> {
    let (dim, lav, unsigned) = book_params(sect_cb)?;
    let book = SPECTRAL_BOOKS[sect_cb as usize];
    let idx = decode_codeword(reader, book)? as i64;
    let base = idx_to_values(idx, dim, lav, unsigned);
    if unsigned {
        if sect_cb == 11 {
            let y = apply_sign_esc(reader, base[2])?;
            let z = apply_sign_esc(reader, base[3])?;
            Some([0, 0, y, z])
        } else {
            let w = apply_sign(reader, base[0])?;
            let x = apply_sign(reader, base[1])?;
            let y = apply_sign(reader, base[2])?;
            let z = apply_sign(reader, base[3])?;
            Some([w, x, y, z])
        }
    } else {
        Some(base)
    }
}

/// Decode one differential scalefactor codeword, returning "dpcm = index - 60"
/// (the "index_offset" of Table 4.150).
pub fn decode_scalefactor(reader: &mut BitReader) -> Option<i32> {
    let idx = decode_codeword(reader, SCALEFACTOR_BOOK)? as i32;
    Some(idx - 60)
}

