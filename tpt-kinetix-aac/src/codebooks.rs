    fn bits_to_bytes(bits: &[u8]) -> Vec<u8> {
        let mut out = Vec::new();
        let mut cur = 0u8;
        let mut n = 0u32;
        for &b in bits {
            cur = (cur << 1) | (b & 1);
            n += 1;
            if n == 8 {
                out.push(cur);
                cur = 0;
                n = 0;
            }
        }
        if n > 0 {
            out.push(cur << (8 - n));
        }
        out
    }

    /// Every codebook must be a valid prefix code: no codeword may be a prefix of
    /// another. This guards against transcription errors in the tables.
    #[test]
    fn codebooks_are_prefix_codes() {
        let books: &[&[(u32, u8)]] = &[SCALEFACTOR_BOOK];
        for book in books.iter().chain(SPECTRAL_BOOKS.iter()) {
            let mut v: Vec<(u32, u32)> = book
                .iter()
                .map(|&(c, l)| (c & ((1u32 << l) - 1), l as u32))
                .collect();
            v.sort();
            for w in v.windows(2) {
                let (c0, l0) = w[0];
                let (c1, l1) = w[1];
                if l0 <= l1 {
                    // The first "l0" bits of the longer codeword (its MSB-side
                    // prefix, stored in the high bits of the low "l1" window)
                    // must not equal the shorter codeword.
                    let high = (c1 >> (l1 - l0)) & ((1u32 << l0) - 1);
                    assert_ne!(
                        c0, high,
                        "prefix collision in codebook (code {c0:#x} len {l0} vs {c1:#x} len {l1})"
                    );
                }
            }
        }
    }

